def test_output_audit_symlink_cannot_overwrite_outside_file(bundle):
    root, inputs, _, path, _ = bundle
    output = root / "dist_submission"
    output.mkdir()
    protected = inputs / "protected.json"
    protected.write_text("protected content", encoding="utf-8")
    try:
        (output / "submission-audit.json").symlink_to(protected)
    except OSError:
        pytest.skip("Host does not permit creating a test symlink")
    with pytest.raises(sub.SubmissionError, match="links"):
        sub.build(path, root)
    assert protected.read_text(encoding="utf-8") == "protected content"


