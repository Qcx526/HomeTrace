def test_roundtrip_test_only_archive_hashes_and_status(bundle):
    root, _, _, config_path, _ = bundle
    report = sub.build(config_path, root)
    assert report["status"] == "TEST_ONLY_VERIFIED"
    assert not report["ready_to_submit"] and not report["officially_verified"] and not report["uploaded"]
    archive_path = root / "dist_submission/TEST_ONLY-candidate-HomeTrace.zip"
    assert report["archive_sha256"] == sub.sha256(archive_path)
    with zipfile.ZipFile(archive_path) as archive:
        assert archive.testzip() is None
        assert report["verified_entries"] == len(archive.namelist())
        for line in archive.read("manifest.sha256").decode().splitlines():
            digest, name = line.split("  ", 1)
            assert hashlib.sha256(archive.read(name)).hexdigest() == digest
        assert "TEST_ONLY" in archive.read("README_提交材料清单.txt").decode()
        assert json.loads(archive.read("PRE_UPLOAD_REVIEW.json"))["manual_checks"]["deadline"] == "PENDING"
        assert not any(".git" in n or "local_data" in n for n in archive.namelist())


