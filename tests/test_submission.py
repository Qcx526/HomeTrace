def office(path, kind, text="Synthetic TEST_ONLY content for packaging tests; not a competition submission."):
    primary = "word/document.xml" if kind == "word" else "ppt/presentation.xml"
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr("[Content_Types].xml", "<Types/>")
        archive.writestr("_rels/.rels", "<Relationships/>")
        archive.writestr(primary, f"<root><t>{text}</t></root>" if kind == "word" else "<root/>")
        if kind != "word":
            archive.writestr("ppt/slides/slide1.xml", f"<root><t>{text}</t></root>")


